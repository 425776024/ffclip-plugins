import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {execFileSync,execSync} from 'node:child_process';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
process.chdir(fileURLToPath(new URL('../../../../',import.meta.url)));
const root=resolve('.local/qa/wasm-gpu-next'),skia=resolve('.local/text-wasm-tools/skia'),build=join(root,'skia-build'),overlay=join(root,'skia-overlay');
await mkdir(overlay,{recursive:true});
let source=await readFile(join(skia,'src/gpu/ganesh/GrRecordingContext.cpp'),'utf8');
const trigger='    // FIXME: Once this is removed from Chrome and Android, rename to fEnable';
if(!source.includes(trigger))throw Error('Path renderer constructor location missing');
source=source.replace(trigger,'    // Experiment only: exact software path coverage with GPU material shading.\n    if (this->options().fDisableTessellationPathRenderer) {\n        prcOptions.fGpuPathRenderers = GpuPathRenderers::kNone;\n    }\n'+trigger);
const cpp=join(overlay,'GrRecordingContext.cpp');await writeFile(cpp,source);
const commands=execFileSync('ninja',['-C',build,'-t','commands'],{encoding:'utf8',maxBuffer:32*1024*1024});
let command=commands.split('\n').find(line=>line.includes('-c ../../../text-wasm-tools/skia/src/gpu/ganesh/GrRecordingContext.cpp '));
if(!command)throw Error('Original compile command missing');
const obj=join(overlay,'gpu.GrRecordingContext.o');
command=command.replace('-c ../../../text-wasm-tools/skia/src/gpu/ganesh/GrRecordingContext.cpp','-c '+cpp).replace('obj/src/gpu/ganesh/gpu.GrRecordingContext.o.d',obj+'.d').replace('-o obj/src/gpu/ganesh/gpu.GrRecordingContext.o','-o '+obj);
await writeFile(join(overlay,'compile-command.txt'),command+'\n');
execSync(command,{cwd:build,stdio:'inherit'});
const library=join(build,'libskia.a');await copyFile(library,join(overlay,'libskia-native-paths.a'));
execFileSync(resolve('.local/text-wasm-tools/emsdk/upstream/bin/llvm-ar'),['r',library,obj],{stdio:'inherit'});
execFileSync('cmake',['--build',join(root,'sdk-build'),'-j8'],{stdio:'inherit'});
console.log('Experimental software path coverage overlay built. Shared Skia source untouched.');
